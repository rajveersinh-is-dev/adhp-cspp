#!/usr/bin/env python3
"""scripts.verify_against_ilp
================================
Independent ground‑truth verification of the ADHP‑CSPP solver.

The script loads problem instances generated by the Rust reference
implementation, solves each instance with a 0‑1 integer linear program
using SciPy/HiGHS, and checks that the solution matches the ADHP output.

The implementation has been modernised for Python 3.10+:

*   Full type annotations and ``typing`` imports.
*   Cleaned‑up imports – removed the unused ``subprocess`` module.
*   Replaced raw string handling with :class:`pathlib.Path` for clarity.
*   Added small helper functions with explicit docstrings.
*   Defensive programming – more specific exception handling and
    validation of the MILP result.
*   Minor performance tweaks (pre‑allocation of the incidence matrix via
    NumPy broadcasting).
*   ``__all__`` to make the public API explicit.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple, Optional

import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds

__all__ = [
    "solve_cspp_ilp",
    "load_instances",
    "verify_instance",
    "main",
]

# ---------------------------------------------------------------------------
# Helper types
# ---------------------------------------------------------------------------
Edge = Dict[str, Any]
Instance = Dict[str, Any]


def solve_cspp_ilp(
    n_nodes: int,
    edges: List[Edge],
    source: int,
    target: int,
    budget: float,
) -> Tuple[Optional[np.ndarray], float, float]:
    """Solve a CSPP instance as a 0‑1 ILP.

    Parameters
    ----------
    n_nodes:
        Number of vertices in the directed graph.
    edges:
        List of edge dictionaries.  Each dictionary must contain the keys
        ``"from"``, ``"to"``, ``"cost"`` and ``"weight"``.
    source:
        Index of the source vertex.
    target:
        Index of the target vertex.
    budget:
        Upper bound on the total weight of the selected path.

    Returns
    -------
    chosen_edges:
        ``np.ndarray`` of edge indices that are selected in the optimal
        solution, or ``None`` if the model is infeasible.
    opt_cost:
        Optimal total cost (``float('inf')`` when infeasible).
    opt_weight:
        Total weight of the selected edges (``float('inf')`` when infeasible).
    """

    m = len(edges)
    if m == 0:
        # Degenerate instance – no edges means infeasible unless source == target.
        return None, float("inf"), float("inf")

    # Extract cost and weight vectors.
    c = np.array([e["cost"] for e in edges], dtype=float)
    w = np.array([e["weight"] for e in edges], dtype=float)

    # Build the node‑arc incidence matrix for flow conservation.
    # Shape: (n_nodes, m)
    A_flow = np.zeros((n_nodes, m), dtype=float)
    for idx, e in enumerate(edges):
        u, v = int(e["from"]), int(e["to"])
        A_flow[u, idx] += 1.0  # outgoing from u
        A_flow[v, idx] -= 1.0  # incoming to v

    # Right‑hand side for flow conservation: +1 at source, -1 at target.
    b_flow = np.zeros(n_nodes, dtype=float)
    b_flow[source] = 1.0
    b_flow[target] = -1.0

    # Append the weight (resource) constraint as the last row.
    A_total = np.vstack([A_flow, w.reshape(1, -1)])
    # Lower bounds: equality for flow rows, -inf for weight row.
    lhs = np.concatenate([b_flow, [-np.inf]])
    # Upper bounds: equality for flow rows, budget for weight row.
    rhs = np.concatenate([b_flow, [budget]])

    constraints = LinearConstraint(A_total, lhs, rhs)
    # All variables are binary (0‑1).
    integrality = np.ones(m, dtype=int)
    bounds = Bounds(0.0, 1.0)

    # Solve the MILP using SciPy's HiGHS backend.
    result = milp(c=c, integrality=integrality, constraints=constraints, bounds=bounds)

    if not result.success or result.x is None:
        # Infeasible or solver failure – treat as infeasible for verification.
        return None, float("inf"), float("inf")

    # Determine which edges are selected (threshold 0.5 to guard against numerical noise).
    chosen_edges = np.where(result.x > 0.5)[0]
    opt_cost = float(result.fun)
    opt_weight = float(w[chosen_edges].sum())
    return chosen_edges, opt_cost, opt_weight


def load_instances(path: Path) -> List[Instance]:
    """Load verification instances from *path*.

    The function raises a ``RuntimeError`` with a clear message if the file
    cannot be read or does not contain valid JSON.
    """
    try:
        with path.open("r", encoding="utf-8") as f:
            data = json.load(f)
    except FileNotFoundError as exc:
        raise RuntimeError(f"Verification file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"Invalid JSON in verification file: {path}") from exc
    if not isinstance(data, list):
        raise RuntimeError("Verification file must contain a JSON array of instances.")
    return data  # type: ignore[return-value]


def verify_instance(inst: Instance) -> Tuple[bool, Optional[str]]:
    """Verify a single instance against the ILP oracle.

    Returns a tuple ``(is_correct, error_message)`` where ``is_correct`` is
    ``True`` when the ADHP result matches the ILP solution.  ``error_message``
    is ``None`` for a correct instance and a human‑readable description for a
    mismatch.
    """
    n_nodes = int(inst["num_nodes"])
    edges = list(inst["edges"])
    source = int(inst["source"])
    target = int(inst["target"])
    budget = float(inst["budget"])

    adhp_status = inst["adhp_status"]
    adhp_cost = float(inst["adhp_cost"])
    adhp_weight = float(inst["adhp_weight"])

    chosen_edges, ilp_cost, ilp_weight = solve_cspp_ilp(
        n_nodes, edges, source, target, budget
    )

    if ilp_cost == float("inf"):
        # ILP proved infeasibility.
        if adhp_status != "Infeasible":
            err = (
                f"Instance {inst['instance_id']} ({inst['family']}): "
                f"ILP proved infeasible, but ADHP returned {adhp_status} "
                f"(cost={adhp_cost})."
            )
            return False, err
        return True, None

    # ILP found a feasible optimum.
    if adhp_status != "Optimal":
        err = (
            f"Instance {inst['instance_id']} ({inst['family']}): "
            f"ILP found feasible optimum (cost={ilp_cost:.4f}, weight={ilp_weight:.4f}), "
            f"but ADHP returned {adhp_status}."
        )
        return False, err

    cost_diff = abs(ilp_cost - adhp_cost)
    rel_diff = cost_diff / max(1.0, abs(ilp_cost))
    if cost_diff > 1e-4 and rel_diff > 1e-5:
        err = (
            f"Instance {inst['instance_id']} ({inst['family']}): Cost mismatch! "
            f"ILP cost={ilp_cost:.6f}, ADHP cost={adhp_cost:.6f}, diff={cost_diff:.6e}."
        )
        return False, err

    if adhp_weight > budget + 1e-6:
        err = (
            f"Instance {inst['instance_id']} ({inst['family']}): ADHP weight "
            f"{adhp_weight:.6f} exceeds budget {budget:.6f}."
        )
        return False, err

    # All checks passed.
    return True, None


def main() -> None:
    """Entry point for the verification script.

    The script expects a JSON file ``results/raw/verification_instances.json``
    generated by the Rust verification oracle.  It prints a concise summary
    and exits with status ``0`` on success or ``1`` when any discrepancy is
    detected.
    """
    print(
        "=== ADHP-CSPP: Ground‑Truth Verification against Independent HiGHS ILP Oracle ==="
    )

    instance_path = Path("results/raw/verification_instances.json")
    try:
        instances = load_instances(instance_path)
    except RuntimeError as exc:
        print(f"Error: {exc}")
        print("Please run `cargo run --bin verify_oracle --release` first.")
        sys.exit(1)

    print(f"Loaded {len(instances)} full problem instances from Rust solver.")
    print("Executing independent 0‑1 ILP solver (SciPy / HiGHS MILP) on each instance…")

    verified_optimal = 0
    verified_infeasible = 0
    total_checked = 0
    discrepancies: List[str] = []

    for inst in instances:
        total_checked += 1
        ok, err = verify_instance(inst)
        if ok:
            if inst["adhp_status"] == "Optimal":
                verified_optimal += 1
            else:
                verified_infeasible += 1
        else:
            discrepancies.append(err)  # type: ignore[arg-type]
            print(f"  [DISCREPANCY] {err}")

        if total_checked % 25 == 0:
            print(
                f"  Processed {total_checked}/{len(instances)} instances: "
                f"{verified_optimal} optimal, {verified_infeasible} infeasible matched."
            )

    print("\n================ VERIFICATION SUMMARY ================")
    print(f"Total instances evaluated: {total_checked}")
    print(f"Exact optimal matches:      {verified_optimal}")
    print(f"Exact infeasible matches:   {verified_infeasible}")
    print(f"Total discrepancies:        {len(discrepancies)}")
    print("=====================================================")

    if discrepancies:
        print(f"FAILED: {len(discrepancies)} discrepancies detected between ADHP and HiGHS ILP.")
        sys.exit(1)
    else:
        print(
            f"SUCCESS: All {total_checked}/{total_checked} instances mathematically verified "
            "against HiGHS ILP oracle with 0 discrepancies."
        )


if __name__ == "__main__":
    main()
